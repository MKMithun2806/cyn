// SMB2 negotiate request. This only asks the server for protocol capabilities;
// it does not authenticate, access files, or modify remote state.
const NEGOTIATE: &[u8] = b"\x00\x00\x00\x54\xfeSMB@\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\n";

pub async fn fingerprint(mut stream: TcpStream) -> Option<ServiceFingerprint> {
    stream.write_all(NEGOTIATE).await.ok()?;
    let mut response = vec![0; 4096];
    let size = stream.read(&mut response).await.ok()?;
    if size < 8 || &response[4..8] != b"\xfeSMB" {
        return None;
    }
    Some(ServiceFingerprint {
        protocol: Some("smb2".into()),
        banner: Some("SMB2 negotiate response".into()),
        ..Default::default()
    })
}
